"""Without a new config key, every backend must receive exactly what it got before.

fixtures/default_path.json was generated by the sensorpushd.py that preceded
the issue-9 changes, from the synthetic inputs stored alongside: the
voltage and sample records of five sensors, rendered as InfluxDB 2 and
InfluxDB 3 line protocol and as VictoriaMetrics import JSON.  The current
code, including the per-backend rendering in _records_for(), must produce
the same bytes.
"""
import datetime
import json
import unittest

from helpers import REPO, DaemonTestCase, fake_writer, sensorpushd

spd = sensorpushd()
FIXTURE = json.loads((REPO / 'tests' / 'fixtures' / 'default_path.json')
                     .read_text(encoding='utf-8'))

try:
    from influxdb_client import Point as Point2
    from influxdb_client.domain.write_precision import WritePrecision as WP2
except ImportError:  # pragma: no cover
    Point2 = None
try:
    from influxdb_client_3.write_client.client.write.point import Point as Point3
    from influxdb_client_3.write_client.domain.write_precision import WritePrecision as WP3
except ImportError:  # pragma: no cover
    Point3 = None


def current_records():
    inp = FIXTURE['inputs']
    querytime = datetime.datetime.strptime(inp['querytime'], '%Y-%m-%dT%X%z')
    return (spd.build_voltage_records(inp['sensors'], 'SensorPush', querytime)
            + spd.process_samples(inp['samples'], inp['sensors'], 'SensorPush',
                                  inp['my_altitude'], False))


class DefaultPathUnchanged(DaemonTestCase):

    def rendered(self):
        """The records as _safe_write hands them to a default backend."""
        d = self.make_daemon([fake_writer()])
        d._note_sensors(FIXTURE['inputs']['sensors'])
        recs = current_records()
        out = d._records_for(d.writers[0], recs)
        self.assertIs(out, recs)
        return out

    @unittest.skipIf(Point2 is None, 'influxdb-client not installed')
    def test_influxdb2(self):
        self.assertEqual([Point2.from_dict(r, write_precision=WP2.NS).to_line_protocol()
                          for r in self.rendered()],
                         FIXTURE['influxdb2_line_protocol'])

    @unittest.skipIf(Point3 is None, 'influxdb3-python not installed')
    def test_influxdb3(self):
        self.assertEqual([Point3.from_dict(r, write_precision=WP3.NS).to_line_protocol()
                          for r in self.rendered()],
                         FIXTURE['influxdb3_line_protocol'])

    def test_victoriametrics(self):
        vm = spd.VMWriter({'url': 'http://vm.invalid', 'verify_ssl': True,
                           'measurement_name': 'SensorPush'})
        self.assertEqual([line for r in self.rendered() for line in vm._to_json_lines(
                              r['measurement'], r['tags'], r['fields'], r['time'])],
                         FIXTURE['victoriametrics_json'])


if __name__ == '__main__':
    unittest.main()
